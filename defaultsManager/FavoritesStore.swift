import Foundation
import Combine

class FavoritesStore: ObservableObject {
    @Published private(set) var favoriteIDs: Set<String> = []

    private let udKey = "defaultsManager.favorites"

    init() {
        if let stored = UserDefaults.standard.array(forKey: udKey) as? [String] {
            favoriteIDs = Set(stored)
        }
    }

    func toggle(_ entry: DefaultEntry) {
        if favoriteIDs.contains(entry.id) {
            favoriteIDs.remove(entry.id)
        } else {
            favoriteIDs.insert(entry.id)
        }
        persist()
    }

    func isFavorite(_ entry: DefaultEntry) -> Bool {
        favoriteIDs.contains(entry.id)
    }

    func favorites(from entries: [DefaultEntry]) -> [DefaultEntry] {
        entries
            .filter { favoriteIDs.contains($0.id) }
            .sorted { $0.key.localizedCaseInsensitiveCompare($1.key) == .orderedAscending }
    }

    /// Generates a shell script containing `defaults write` commands for all favorites.
    func exportScript(for entries: [DefaultEntry]) -> String {
        let formatter = ISO8601DateFormatter()
        var lines: [String] = [
            "#!/bin/bash",
            "# macOS Defaults — Favorites",
            "# Generated by defaultsManager on \(formatter.string(from: Date()))",
            "# Run with:  bash <filename>",
            "",
        ]

        let grouped = Dictionary(grouping: entries, by: { $0.category })
        for category in grouped.keys.sorted() {
            lines.append("# ── \(category) ──────────────────────────")
            for entry in (grouped[category] ?? []).sorted(by: { $0.key < $1.key }) {
                let domainArg: String
                switch entry.domain {
                case "NSGlobalDomain", "Apple Global Domain", "":
                    domainArg = "-globalDomain"
                default:
                    domainArg = entry.domain
                }
                lines.append("defaults write \(domainArg) \(entry.key) \(entry.type.defaultsFlag) \(entry.value)")
            }
            lines.append("")
        }

        return lines.joined(separator: "\n")
    }

    private func persist() {
        UserDefaults.standard.set(Array(favoriteIDs), forKey: udKey)
    }
}
